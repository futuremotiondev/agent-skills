#Requires -Version 7.1
using namespace System.IO

<#
.SYNOPSIS
    Regenerates Context/generated/api-index.md — an index of the public C#
    type surface, scanned from *.cs source.

.DESCRIPTION
    Seeded by the context-engine csharp adapter; project-owned — tune
    the exclusions (or replace the regex scan with a Roslyn walk) freely.

    The scan is intentionally lightweight: a line-based regex for public type
    declarations. It does not resolve partial classes, nested types'
    visibility chains, or conditional compilation — good enough for an
    orientation index, not a compiler.

    Contract (Context/scripts/README.md): standalone, fast, writes exactly one
    banner-prefixed artifact into Context/generated/.
#>

[CmdletBinding()]
param()

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

$repoRoot = if ($env:CLAUDE_PROJECT_DIR) { $env:CLAUDE_PROJECT_DIR } else { (Get-Location).ProviderPath }
$outPath  = [Path]::Combine($repoRoot, 'Context', 'generated', 'api-index.md')

# Directories never scanned. Add project-specific exclusions here.
$excludeDirPattern = '[\\/](bin|obj|\.git|\.claude|node_modules|TestData|packages)[\\/]'

$typePattern = '^\s*public\s+(?:static\s+|sealed\s+|abstract\s+|partial\s+|readonly\s+|ref\s+|unsafe\s+)*' +
               '(?<kind>class|record\s+struct|record\s+class|record|interface|enum|struct)\s+' +
               '(?<name>[A-Za-z_]\w*(?:<[^>{(]*>)?)'
$nsFilePattern  = '^\s*namespace\s+(?<ns>[\w.]+)\s*;'
$nsBlockPattern = '^\s*namespace\s+(?<ns>[\w.]+)\s*(\{)?\s*$'

$rows = [System.Collections.Generic.List[object]]::new()
$files = Get-ChildItem -LiteralPath $repoRoot -Recurse -File -Filter '*.cs' |
    Where-Object { $_.FullName -notmatch $excludeDirPattern -and $_.Name -notmatch '\.(Designer|g|g\.i)\.cs$' }

foreach ($file in $files) {
    $ns = ''
    foreach ($line in [File]::ReadLines($file.FullName)) {
        if (-not $ns) {
            if ($line -match $nsFilePattern -or $line -match $nsBlockPattern) { $ns = $Matches['ns'] }
        }
        if ($line -match $typePattern) {
            $rows.Add([pscustomobject]@{
                Type      = $Matches['name']
                Kind      = ($Matches['kind'] -replace '\s+', ' ')
                Namespace = $ns
                File      = ($file.FullName.Substring($repoRoot.Length + 1) -replace '\\', '/')
            })
        }
    }
}

$rows = $rows | Sort-Object Namespace, Type

$sb = [System.Text.StringBuilder]::new()
$null = $sb.AppendLine('<!-- GENERATED FILE — DO NOT EDIT — regenerated by Context/scripts/regenerate-api-index.ps1 -->')
$null = $sb.AppendLine('<!-- Source: regex scan of **/*.cs for public type declarations (bin/obj/tests excluded) -->')
$null = $sb.AppendLine("<!-- Last run: $(Get-Date -AsUTC -Format 'yyyy-MM-ddTHH:mm:ssZ') -->")
$null = $sb.AppendLine('')
$null = $sb.AppendLine('# Public API Index')
$null = $sb.AppendLine('')
$null = $sb.AppendLine("$(@($rows).Count) public type(s).")
$null = $sb.AppendLine('')
$null = $sb.AppendLine('| Type | Kind | Namespace | File |')
$null = $sb.AppendLine('| ---- | ---- | --------- | ---- |')
foreach ($row in $rows) {
    $null = $sb.AppendLine("| ``$($row.Type)`` | $($row.Kind) | $($row.Namespace) | [$($row.File)](../../$($row.File)) |")
}

$null = [Directory]::CreateDirectory([Path]::GetDirectoryName($outPath))
[File]::WriteAllText($outPath, $sb.ToString().Replace("`r`n", "`n"), [System.Text.UTF8Encoding]::new($false))
Write-Host "api-index: $(@($rows).Count) public type(s) -> Context/generated/api-index.md"
exit 0
