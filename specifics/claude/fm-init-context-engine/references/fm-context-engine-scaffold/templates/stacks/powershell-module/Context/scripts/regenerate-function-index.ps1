#Requires -Version 7.1
using namespace System.IO
using namespace System.Management.Automation.Language

<#
.SYNOPSIS
    Regenerates Context/generated/function-index.md — an index of the module's
    function definitions, discovered via AST parsing of *.ps1 files.

.DESCRIPTION
    Seeded by the context-engine powershell-module adapter; project-owned —
    tune the exclusions or scope it to the module's Public/ tree freely.

    AST parsing (not dot-sourcing): no side effects, no module load, no
    missing-dependency errors. Top-level function definitions only — nested
    helpers are deliberately ignored.

    Contract (Context/scripts/README.md): standalone, fast, writes exactly one
    banner-prefixed artifact into Context/generated/.
#>

[CmdletBinding()]
param()

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

$repoRoot = if ($env:CLAUDE_PROJECT_DIR) { $env:CLAUDE_PROJECT_DIR } else { (Get-Location).ProviderPath }
$outPath  = [Path]::Combine($repoRoot, 'Context', 'generated', 'function-index.md')

# Directories/files never scanned. Add project-specific exclusions here.
$excludePathPattern = '[\\/](\.git|\.claude|Context|node_modules|bin|obj|TestData)[\\/]|\.Tests\.ps1$'

$rows = [System.Collections.Generic.List[object]]::new()
$files = Get-ChildItem -LiteralPath $repoRoot -Recurse -File -Filter '*.ps1' |
    Where-Object { $_.FullName -notmatch $excludePathPattern }

foreach ($file in $files) {
    $errors = $null
    $ast = [Parser]::ParseFile($file.FullName, [ref]$null, [ref]$errors)
    if ($errors.Count) { continue }  # unparsable files are skipped, not fatal

    # Top-level functions only: FindAll with searchNestedScriptBlocks=$false
    # still descends into some containers, so filter to parents that are the
    # root-level statement block.
    $functions = $ast.FindAll({ param($node) $node -is [FunctionDefinitionAst] }, $false)
    foreach ($fn in $functions) {
        $exported = $fn.Name -notmatch '^(Internal|Private|Helper)-'
        $rows.Add([pscustomobject]@{
            Function = $fn.Name
            Exported = if ($exported) { 'yes' } else { 'internal' }
            File     = ($file.FullName.Substring($repoRoot.Length + 1) -replace '\\', '/')
            Line     = $fn.Extent.StartLineNumber
        })
    }
}

$rows = $rows | Sort-Object Function

$sb = [System.Text.StringBuilder]::new()
$null = $sb.AppendLine('<!-- GENERATED FILE — DO NOT EDIT — regenerated by Context/scripts/regenerate-function-index.ps1 -->')
$null = $sb.AppendLine('<!-- Source: AST walk of **/*.ps1 for top-level function definitions (tests/Context excluded) -->')
$null = $sb.AppendLine("<!-- Last run: $(Get-Date -AsUTC -Format 'yyyy-MM-ddTHH:mm:ssZ') -->")
$null = $sb.AppendLine('')
$null = $sb.AppendLine('# Function Index')
$null = $sb.AppendLine('')
$null = $sb.AppendLine("$(@($rows).Count) function(s). ``Exported = internal`` marks Internal-/Private-/Helper- prefixed names excluded from release manifests by convention.")
$null = $sb.AppendLine('')
$null = $sb.AppendLine('| Function | Exported | File |')
$null = $sb.AppendLine('| -------- | -------- | ---- |')
foreach ($row in $rows) {
    $null = $sb.AppendLine("| ``$($row.Function)`` | $($row.Exported) | [$($row.File):$($row.Line)](../../$($row.File)#L$($row.Line)) |")
}

$null = [Directory]::CreateDirectory([Path]::GetDirectoryName($outPath))
[File]::WriteAllText($outPath, $sb.ToString().Replace("`r`n", "`n"), [System.Text.UTF8Encoding]::new($false))
Write-Host "function-index: $(@($rows).Count) function(s) -> Context/generated/function-index.md"
exit 0
