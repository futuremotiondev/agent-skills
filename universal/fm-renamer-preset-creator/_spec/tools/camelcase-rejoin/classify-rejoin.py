OUT_TSV = ROOT / 'data' / 'camelcase-rejoin.tsv'
PROBE = Path(__file__).resolve().parent / 'camelcase-splitmap.probes.psd1'
CAMEL = re.compile(r'[a-z0-9][A-Z]|[A-Z][A-Z][a-z]')   # transitions where CleanUp may insert a space

